CREATE TABLE products (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    unit VARCHAR(5) NOT NULL,
    category VARCHAR(50) NOT NULL,
    quantity INT NOT NULL DEFAULT 0,
    price DECIMAL(7, 2) NOT NULL DEFAULT 0.00,
    date_added DATE NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT chk_products_unit CHECK (unit IN ('шт', 'кг', 'л', 'м', 'уп')),
    CONSTRAINT chk_products_quantity CHECK (quantity >= 0),
    CONSTRAINT chk_products_price CHECK (price >= 0)
);

CREATE TABLE shops (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    address VARCHAR(200) NOT NULL,
    phone VARCHAR(20),
    CONSTRAINT chk_shops_phone CHECK (
        phone IS NULL OR phone ~ '^[-0-9+() ]{10,20}$'
    )
);

CREATE TABLE shop_products (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_shop INT NOT NULL,
    id_product INT NOT NULL,
    quantity INT NOT NULL DEFAULT 0,
    CONSTRAINT uq_shop_products_shop_product UNIQUE (id_shop, id_product),
    CONSTRAINT chk_shop_products_quantity CHECK (quantity >= 0),
    CONSTRAINT fk_shop_products_shop FOREIGN KEY (id_shop)
        REFERENCES shops (id) ON DELETE RESTRICT,
    CONSTRAINT fk_shop_products_product FOREIGN KEY (id_product)
        REFERENCES products (id) ON DELETE RESTRICT
);

CREATE INDEX idx_shop_products_product
    ON shop_products (id_product);

CREATE TABLE orders (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_shop INT NOT NULL,
    id_product INT NOT NULL,
    quantity_req INT NOT NULL,
    date_order DATE NOT NULL DEFAULT CURRENT_DATE,
    status VARCHAR(11) NOT NULL DEFAULT 'new',
    CONSTRAINT chk_orders_quantity_req CHECK (quantity_req > 0),
    CONSTRAINT chk_orders_status CHECK (status IN ('new', 'in progress', 'done')),
    CONSTRAINT fk_orders_shop FOREIGN KEY (id_shop)
        REFERENCES shops (id) ON DELETE RESTRICT,
    CONSTRAINT fk_orders_product FOREIGN KEY (id_product)
        REFERENCES products (id) ON DELETE RESTRICT
);

CREATE INDEX idx_orders_shop_date_status
    ON orders (id_shop, date_order, status);

CREATE INDEX idx_orders_product
    ON orders (id_product);
