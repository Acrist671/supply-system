CREATE TABLE stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_product INTEGER NOT NULL REFERENCES products (id) ON DELETE RESTRICT,
    id_shop INTEGER REFERENCES shops (id) ON DELETE RESTRICT,
    id_order INTEGER UNIQUE REFERENCES orders (id) ON DELETE RESTRICT,
    movement_type VARCHAR(10) NOT NULL,
    quantity BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_stock_movements_quantity CHECK (quantity > 0),
    CONSTRAINT chk_stock_movements_type CHECK (
        (movement_type = 'receipt' AND id_shop IS NULL AND id_order IS NULL)
        OR (movement_type = 'shipment' AND id_shop IS NOT NULL AND id_order IS NOT NULL)
    )
);

CREATE INDEX idx_stock_movements_created_at ON stock_movements (created_at DESC, id DESC);
CREATE INDEX idx_stock_movements_product ON stock_movements (id_product);
